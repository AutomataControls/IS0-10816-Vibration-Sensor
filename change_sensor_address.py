def get_crc(datas, dlen):
    tempH = 0xff
    tempL = 0xff
    for i in range(0, dlen):
        tempIndex = (tempH ^ datas[i]) & 0xff
        tempH = (tempL ^ auchCRCHi[tempIndex]) & 0xff
        tempL = auchCRCLo[tempIndex]
    return (tempH << 8) | tempL

def get_write_bytes(devid, regAddr, sValue):
    tempBytes = [None] * 8
    tempBytes[0] = devid
    tempBytes[1] = 0x06  # Write function code
    tempBytes[2] = regAddr >> 8
    tempBytes[3] = regAddr & 0xff
    tempBytes[4] = sValue >> 8
    tempBytes[5] = sValue & 0xff
    tempCrc = get_crc(tempBytes, 6)
    tempBytes[6] = tempCrc >> 8
    tempBytes[7] = tempCrc & 0xff
    return bytes(tempBytes)

def unlock(ser, address):
    """Send unlock command"""
    cmd = get_write_bytes(address, 0x69, 0xb588)
    ser.write(cmd)
    print(f"Unlock command sent: {cmd.hex()}")

def save(ser, address):
    """Send save command"""
    cmd = get_write_bytes(address, 0x00, 0x0000)
    ser.write(cmd)
    print(f"Save command sent: {cmd.hex()}")

def change_address(ser, current_addr, new_addr):
    """Change sensor address"""
    # 1. Unlock the device
    print(f"\nStep 1: Unlocking device at address 0x{current_addr:02X}")
    unlock(ser, current_addr)
    time.sleep(0.2)
    
    # 2. Write new address to register 0x1A (26)
    print(f"\nStep 2: Writing new address 0x{new_addr:02X} to register 0x1A")
    cmd = get_write_bytes(current_addr, 0x1A, new_addr)
    ser.write(cmd)
    print(f"Address change command sent: {cmd.hex()}")
    time.sleep(0.2)
    
    # 3. Save the configuration
    print(f"\nStep 3: Saving configuration")
    save(ser, current_addr)
    time.sleep(0.2)
    
    print(f"\nAddress changed from 0x{current_addr:02X} to 0x{new_addr:02X}")
    print("Please power cycle the sensor for changes to take effect")

